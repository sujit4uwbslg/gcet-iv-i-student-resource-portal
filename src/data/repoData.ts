export function getRawUrl(path: string): string {
  // Encode URI components cleanly
  const encodedPath = path.split('/').map(segment => encodeURIComponent(segment)).join('/');
  return `${RAW_BASE_URL}/${encodedPath}`;
}

export function getViewUrl(path: string): string {
  const encodedPath = path.split('/').map(segment => encodeURIComponent(segment)).join('/');
  return `${REPO_URL}/blob/${REPO_BRANCH}/${encodedPath}`;
}

